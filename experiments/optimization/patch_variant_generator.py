"""
Patch variant generator for M4 iterative harness optimization.

This module generates a small set of constrained M4 candidate patch variants
from a base proposal patch generated by:

    experiments/optimization/harness_proposer.py

Purpose:
- Avoid manual patch tuning after validation feedback.
- Generate predefined, guardrail-constrained patch variants.
- Keep all variants within editable harness modules only.
- Preserve anti-leakage constraints: do not expose hidden supports annotations.
- Support iterative optimization loops by producing candidate patches per
  iteration.

Typical input:
    outputs/search/<run_name>/proposals/M4_base_proposal_001_patch.json

Typical output:
    outputs/search/<run_name>/variant_candidates/
    ├─ M4_iter01_full_patch_patch.json
    ├─ M4_iter01_relaxed_trigger_patch.json
    ├─ M4_iter01_action_filter_only_patch.json
    ├─ M4_iter01_repair_prompt_only_patch.json
    ├─ M4_iter01_minimal_m3_plus_filter_patch.json
    └─ variant_manifest.csv

Recommended downstream:
    candidate_validator.py
    candidate_screening.py
    run_search_candidate.py
    optimization_loop.py
"""

from __future__ import annotations

import argparse
import copy
import csv
import json
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any


# ============================================================
# Constants
# ============================================================

EDITABLE_MODULES = [
    "source_policy",
    "evidence_table_format",
    "prompt_instructions",
    "action_filter_rules",
    "repair_prompt",
    "repair_trigger_thresholds",
]

FROZEN_MODULES = [
    "action_ontology",
    "allowed_schema",
    "candidate_labels",
    "datasets",
    "evaluator",
    "gold_labels",
    "hidden_supports_annotations",
    "metric_definitions",
    "preprocessed_files",
    "proxy_evidence_builder",
    "task_sampling",
    "test_split",
]

SAFE_EVIDENCE_COLUMNS = [
    "evidence_id",
    "source",
    "field",
    "statistic",
    "direction",
    "value",
    "window",
    "role",
]

FORBIDDEN_COLUMNS = [
    "supports",
]

OUT_OF_SCOPE_ACTIONS = [
    "adjust_parameter",
    "shutdown",
]

DEFAULT_REPAIR_TRIGGERS = {
    "schema_invalid": True,
    "F3": True,
    "F4": True,
    "F5": True,
    "F6": True,
    "F7": True,
    "F8": True,
    "unsafe_recommendation_rate_gt": 0.0,
    "unsupported_claim_rate_gt": None,
}

SUPPORTED_VARIANTS = [
    "full_patch",
    "relaxed_trigger",
    "action_filter_only",
    "repair_prompt_only",
    "minimal_m3_plus_filter",
]


# ============================================================
# Dataclasses
# ============================================================

@dataclass(frozen=True)
class VariantRecord:
    candidate_id: str
    variant_type: str
    patch_path: str
    base_candidate_id: str
    iteration: int
    description: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


# ============================================================
# I/O
# ============================================================

def read_json(path: str | Path) -> dict[str, Any]:
    path = Path(path)

    if not path.exists():
        raise FileNotFoundError(f"Patch JSON file not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, dict):
        raise TypeError(f"Patch JSON must contain a dictionary: {path}")

    return data


def write_json(path: str | Path, obj: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2, default=str)


def write_manifest_csv(path: str | Path, records: list[VariantRecord]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "candidate_id",
        "variant_type",
        "patch_path",
        "base_candidate_id",
        "iteration",
        "description",
    ]

    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for record in records:
            writer.writerow(record.to_dict())


def write_manifest_json(path: str | Path, records: list[VariantRecord]) -> None:
    write_json(path, [record.to_dict() for record in records])


# ============================================================
# Guardrails and normalization
# ============================================================

def normalize_patch_base(patch: dict[str, Any]) -> dict[str, Any]:
    """
    Normalize fields that every executable M4 patch must have.

    This function does not change datasets, labels, evaluator, metric
    definitions, test split, or proxy evidence builder.
    """
    patch = copy.deepcopy(patch)

    patch["editable_modules"] = list(EDITABLE_MODULES)
    patch["frozen_modules"] = list(FROZEN_MODULES)

    evidence_format = patch.setdefault("evidence_table_format", {})
    evidence_format["proposed_columns"] = [
        col for col in evidence_format.get("proposed_columns", SAFE_EVIDENCE_COLUMNS)
        if col not in {"supports", "gold_label", "gold", "ground_truth", "target_label", "true_label"}
    ]

    if not evidence_format["proposed_columns"]:
        evidence_format["proposed_columns"] = list(SAFE_EVIDENCE_COLUMNS)

    forbidden_columns = set(str(c) for c in evidence_format.get("forbidden_columns", []))
    forbidden_columns.add("supports")
    evidence_format["forbidden_columns"] = sorted(forbidden_columns)

    action_rules = patch.setdefault("action_filter_rules", {})
    out_of_scope = set(str(a) for a in action_rules.get("out_of_scope_actions", []))
    out_of_scope.update(OUT_OF_SCOPE_ACTIONS)
    action_rules["out_of_scope_actions"] = sorted(out_of_scope)

    repair_triggers = patch.setdefault("repair_trigger_thresholds", {})
    for key, value in DEFAULT_REPAIR_TRIGGERS.items():
        repair_triggers.setdefault(key, value)

    return patch


def validate_no_supports_exposure(patch: dict[str, Any]) -> None:
    evidence_format = patch.get("evidence_table_format", {})
    proposed_columns = set(str(c) for c in evidence_format.get("proposed_columns", []))
    forbidden_columns = set(str(c) for c in evidence_format.get("forbidden_columns", []))

    if "supports" in proposed_columns:
        raise ValueError(
            f"Candidate {patch.get('candidate_id')} exposes forbidden column 'supports'."
        )

    if "supports" not in forbidden_columns:
        raise ValueError(
            f"Candidate {patch.get('candidate_id')} does not list 'supports' as forbidden."
        )


def set_candidate_identity(
    patch: dict[str, Any],
    *,
    candidate_id: str,
    variant_type: str,
    base_candidate_id: str,
    iteration: int,
) -> dict[str, Any]:
    patch = copy.deepcopy(patch)

    patch["candidate_id"] = candidate_id
    patch["base_method"] = "M3"

    patch.setdefault("expected_effects", {})
    patch["expected_effects"]["variant_type"] = variant_type
    patch["expected_effects"]["base_candidate_id"] = base_candidate_id
    patch["expected_effects"]["iteration"] = iteration

    patch.setdefault("rationale", "")
    patch["rationale"] = (
        f"Variant '{variant_type}' generated from base candidate "
        f"'{base_candidate_id}' at optimization iteration {iteration}. "
        f"{patch.get('rationale', '')}"
    ).strip()

    return patch


def make_candidate_id(
    *,
    prefix: str,
    iteration: int,
    variant_type: str,
) -> str:
    return f"{prefix}_iter{iteration:02d}_{variant_type}"


