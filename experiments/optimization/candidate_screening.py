def records_to_dataframe(records: list[CandidateRecord]) -> pd.DataFrame:
    rows = []

    for record in records:
        rows.append(
            {
                "candidate_id": record.candidate_id,
                "selected": record.selected,
                "rank": record.rank,
                "valid": record.valid,
                "n_errors": record.n_errors,
                "n_warnings": record.n_warnings,
                "screening_score": record.screening_score,
                "duplicate_of": record.duplicate_of,
                "patch_signature": record.patch_signature,
                "targeted_failures": ",".join(record.targeted_failures),
                "patch_path": record.patch_path,
                "validation_path": record.validation_path,
                "notes": " | ".join(record.notes),
                "errors": json.dumps(record.errors, ensure_ascii=False),
                "warnings": json.dumps(record.warnings, ensure_ascii=False),
            }
        )

    return pd.DataFrame(rows)


def write_screening_outputs(
    *,
    records: list[CandidateRecord],
    output_dir: str | Path,
    copy_selected_patches: bool = True,
) -> None:
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    df = records_to_dataframe(records)
    df.to_csv(output_dir / "screened_candidates.csv", index=False)

    write_jsonl(
        output_dir / "screened_candidates.jsonl",
        [record.to_dict() for record in records],
    )

    selected = [record for record in records if record.selected]

    summary = {
        "n_total_candidates": len(records),
        "n_valid_candidates": sum(1 for r in records if r.valid),
        "n_selected_candidates": len(selected),
        "selected_candidate_ids": [r.candidate_id for r in selected],
        "duplicates": {
            r.candidate_id: r.duplicate_of
            for r in records
            if r.duplicate_of is not None
        },
        "max_rank": max([r.rank for r in selected if r.rank is not None], default=None),
    }

    write_json(output_dir / "screening_summary.json", summary)

    if copy_selected_patches:
        patch_out_dir = output_dir / "selected_candidate_patches"
        patch_out_dir.mkdir(parents=True, exist_ok=True)

        for record in selected:
            src = Path(record.patch_path)
            dst = patch_out_dir / src.name
            shutil.copy2(src, dst)


