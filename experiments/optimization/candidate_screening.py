def main() -> None:
    parser = argparse.ArgumentParser(
        description="Pre-validation screening for M4 candidate patches."
    )

    parser.add_argument(
        "--patches",
        required=True,
        help="Patch JSON file or directory containing *_patch.json files.",
    )
    parser.add_argument(
        "--validations",
        required=True,
        help="Validation JSON file or directory containing *_validation.json files.",
    )
    parser.add_argument(
        "--output-dir",
        required=True,
        help="Output directory for screened candidate files.",
    )
    parser.add_argument(
        "--max-candidates",
        type=int,
        default=4,
        help="Maximum candidates to retain for validation-set evaluation.",
    )
    parser.add_argument(
        "--disallow-warnings",
        action="store_true",
        help="If set, candidates with warnings are not selected.",
    )
    parser.add_argument(
        "--keep-duplicates",
        action="store_true",
        help="If set, duplicate semantic patches are not removed.",
    )
    parser.add_argument(
        "--no-copy-patches",
        action="store_true",
        help="If set, do not copy selected patches into selected_candidate_patches/.",
    )

    args = parser.parse_args()

    records = screen_candidates(
        patch_dir_or_file=args.patches,
        validation_dir_or_file=args.validations,
        max_candidates=args.max_candidates,
        allow_warnings=not args.disallow_warnings,
        keep_duplicates=args.keep_duplicates,
    )

    write_screening_outputs(
        records=records,
        output_dir=args.output_dir,
        copy_selected_patches=not args.no_copy_patches,
    )

    df = records_to_dataframe(records)

    print("=== Candidate Screening Results ===")
    if df.empty:
        print("No candidate records found.")
    else:
        preview_cols = [
            "candidate_id",
            "selected",
            "rank",
            "valid",
            "n_errors",
            "n_warnings",
            "screening_score",
            "duplicate_of",
            "targeted_failures",
        ]
        print(df[[col for col in preview_cols if col in df.columns]])

    print("\nSaved outputs:")
    print(f"- {Path(args.output_dir) / 'screened_candidates.csv'}")
    print(f"- {Path(args.output_dir) / 'screened_candidates.jsonl'}")
    print(f"- {Path(args.output_dir) / 'screening_summary.json'}")
    print(f"- {Path(args.output_dir) / 'selected_candidate_patches'}")


if __name__ == "__main__":
    main()
