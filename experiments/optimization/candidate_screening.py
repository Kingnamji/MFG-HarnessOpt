"""
Candidate screening for M4 harness patches.

This module performs pre-validation screening of candidate patches generated by:

    experiments/optimization/harness_proposer.py

and validated by:

    experiments/optimization/candidate_validator.py

At this stage, candidate_screening.py does not evaluate candidates on the
validation split. It only prepares a clean candidate list for run_validation.py.

Responsibilities:
- Load candidate patches.
- Load candidate validation results.
- Keep only valid candidates.
- Remove duplicate or near-duplicate patches using a canonical patch signature.
- Rank remaining candidates using simple pre-validation heuristics:
    1. fewer validation errors
    2. fewer warnings
    3. targets more high-priority failure types
    4. does not expose supports
    5. contains action-filter and repair-prompt changes
- Export screened candidate list for validation runner.

Typical input:
    outputs/search/<run_name>/proposals/
    outputs/search/<run_name>/validated_candidates/

Typical output:
    outputs/search/<run_name>/screened_candidates/
    ├─ screened_candidates.csv
    ├─ screened_candidates.jsonl
    ├─ screening_summary.json
    └─ selected_candidate_patches/
       └─ <candidate_id>_patch.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import pandas as pd


# ============================================================
# Constants
# ============================================================

HIGH_PRIORITY_FAILURES = [
    "F10",
    "F8",
    "F7",
    "F6",
    "F5",
    "F2",
    "F1",
    "F9",
    "F4",
    "F3",
]

REQUIRED_PATCH_FIELDS = [
    "candidate_id",
    "base_method",
    "source_policy",
    "evidence_table_format",
    "prompt_instructions",
    "action_filter_rules",
    "repair_prompt",
    "repair_trigger_thresholds",
    "expected_effects",
]


# ============================================================
# Data classes
# ============================================================

@dataclass(frozen=True)
class CandidateRecord:
    candidate_id: str
    patch_path: str
    validation_path: str | None
    valid: bool
    n_errors: int
    n_warnings: int
    patch_signature: str
    screening_score: float
    duplicate_of: str | None = None
    selected: bool = False
    rank: int | None = None
    targeted_failures: list[str] = field(default_factory=list)
    warnings: list[dict[str, Any]] = field(default_factory=list)
    errors: list[dict[str, Any]] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


# ============================================================
# I/O
# ============================================================

def read_json(path: str | Path) -> dict[str, Any]:
    path = Path(path)

    if not path.exists():
        raise FileNotFoundError(f"JSON file not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, dict):
        raise TypeError(f"Expected JSON object/dict: {path}")

    return data


def write_json(path: str | Path, obj: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2, default=str)


def write_jsonl(path: str | Path, rows: list[dict[str, Any]]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")


def find_patch_files(patch_dir_or_file: str | Path) -> list[Path]:
    path = Path(patch_dir_or_file)

    if path.is_file():
        return [path]

    if not path.exists():
        raise FileNotFoundError(f"Patch path not found: {path}")

    patch_files = sorted(path.glob("*_patch.json"))

    if not patch_files:
        patch_files = sorted(path.glob("*.json"))

    return patch_files


def find_validation_files(validation_dir_or_file: str | Path | None) -> dict[str, Path]:
    if validation_dir_or_file is None:
        return {}

    path = Path(validation_dir_or_file)

    if not path.exists():
        raise FileNotFoundError(f"Validation path not found: {path}")

    files: list[Path]

    if path.is_file():
        files = [path]
    else:
        files = sorted(path.glob("*_validation.json"))

    out: dict[str, Path] = {}

    for file in files:
        try:
            data = read_json(file)
        except Exception:
            continue

        candidate_id = data.get("candidate_id")
        if candidate_id:
            out[str(candidate_id)] = file

    return out


# ============================================================
# Canonicalization / duplicate detection
# ============================================================

def strip_nonsemantic_fields(patch: dict[str, Any]) -> dict[str, Any]:
    """
    Remove fields that should not define semantic uniqueness.

    candidate_id and rationale can differ even when the effective patch is same.
    """
    ignored = {
        "candidate_id",
        "rationale",
        "risks",
        "expected_effects",
        "objective",
    }

    return {
        key: value
        for key, value in patch.items()
        if key not in ignored
    }


def canonicalize_patch(patch: dict[str, Any]) -> str:
    from experiments.harness.m4_patched import (format_m4_patch_instructions,
        format_m4_repair_instructions,get_m4_evidence_columns)
    from experiments.llm.report_contract import REPORT_CONTRACT_VERSION
    triggers=dict(patch.get('repair_trigger_thresholds',{}))
    for key in ['schema_invalid','F3','F4','F5','F6','F7','F8']:triggers.setdefault(key,True)
    triggers.setdefault('unsafe_recommendation_rate_gt',0.0)
    triggers.setdefault('unsupported_claim_rate_gt',None)
    if all(triggers.get(k) is True for k in ['schema_invalid','F3','F4','F5','F6','F7','F8']):
        # Under the current observable verifier, positive unsupported rate
        # already implies one of these mandatory failures (or invalid schema).
        triggers['unsupported_claim_rate_gt']=None
    semantic=dict(report_contract=REPORT_CONTRACT_VERSION,
        initial_instructions=format_m4_patch_instructions(patch),
        repair_instructions=format_m4_repair_instructions(patch),
        evidence_columns=get_m4_evidence_columns(patch),repair_triggers=triggers)
    return json.dumps(
        semantic,
        ensure_ascii=False,
        sort_keys=True,
        default=str,
        separators=(",", ":"),
    )


def patch_signature(patch: dict[str, Any]) -> str:
    canonical = canonicalize_patch(patch)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()[:16]


# ============================================================
# Validation result handling
# ============================================================

def load_validation_result(
    *,
    candidate_id: str,
    validation_files: dict[str, Path],
) -> tuple[bool, int, int, list[dict[str, Any]], list[dict[str, Any]], str | None]:
    """
    Return:
        valid, n_errors, n_warnings, errors, warnings, validation_path
    """
    path = validation_files.get(candidate_id)

    if path is None:
        return False, 1, 0, [
            {
                "severity": "error",
                "code": "missing_validation_result",
                "message": f"No validation result found for candidate_id={candidate_id}",
                "location": "validation",
            }
        ], [], None

    data = read_json(path)

    return (
        bool(data.get("valid", False)),
        int(data.get("n_errors", 0) or 0),
        int(data.get("n_warnings", 0) or 0),
        list(data.get("errors", []) or []),
        list(data.get("warnings", []) or []),
        str(path),
    )


# ============================================================
# Screening score
# ============================================================

def get_targeted_failures(patch: dict[str, Any]) -> list[str]:
    expected = patch.get("expected_effects", {})
    failures = expected.get("targeted_failure_reductions", [])

    out = []
    for item in failures:
        item = str(item).upper().strip()
        if item.startswith("F"):
            out.append(item)

    return out


def score_patch_prevalidation(
    *,
    patch: dict[str, Any],
    valid: bool,
    n_errors: int,
    n_warnings: int,
) -> tuple[float, list[str]]:
    """
    Heuristic pre-validation screening score.

    This is not the final J_mfg objective. Final selection must use validation
    performance after candidates are executed on the validation split.
    """
    notes: list[str] = []
    score = 0.0

    if valid:
        score += 100.0
        notes.append("valid_candidate")
    else:
        score -= 100.0
        notes.append("invalid_candidate")

    score -= 10.0 * n_errors
    score -= 1.0 * n_warnings

    targeted = get_targeted_failures(patch)
    priority_weights = {
        failure_id: len(HIGH_PRIORITY_FAILURES) - idx
        for idx, failure_id in enumerate(HIGH_PRIORITY_FAILURES)
    }

    for failure_id in targeted:
        weight = priority_weights.get(failure_id, 1)
        score += float(weight)
        notes.append(f"targets_{failure_id}")

    evidence_format = patch.get("evidence_table_format", {})
    proposed_columns = evidence_format.get("proposed_columns", [])
    forbidden_columns = evidence_format.get("forbidden_columns", [])

    if "supports" not in proposed_columns and "supports" in forbidden_columns:
        score += 5.0
        notes.append("supports_hidden")

    action_rules = patch.get("action_filter_rules", {}).get("rules", [])
    if action_rules:
        score += 3.0
        notes.append("has_action_filter_rules")

    repair_prompt = patch.get("repair_prompt", {})
    if repair_prompt.get("repair_instructions") or repair_prompt.get("failure_specific_repairs"):
        score += 3.0
        notes.append("has_repair_prompt_changes")

    source_policy = patch.get("source_policy", {})
    if source_policy.get("proposed_changes"):
        score += 1.0
        notes.append("has_source_policy_changes")

    missing_required = [field for field in REQUIRED_PATCH_FIELDS if field not in patch]
    if missing_required:
        score -= 5.0 * len(missing_required)
        notes.append(f"missing_required_fields={missing_required}")

    return score, notes


# ============================================================
# Main screening
# ============================================================

def build_candidate_records(
    *,
    patch_files: list[Path],
    validation_files: dict[str, Path],
) -> list[CandidateRecord]:
    records: list[CandidateRecord] = []

    for patch_path in patch_files:
        patch = read_json(patch_path)
        candidate_id = str(patch.get("candidate_id", patch_path.stem.replace("_patch", "")))

        valid, n_errors, n_warnings, errors, warnings, validation_path = load_validation_result(
            candidate_id=candidate_id,
            validation_files=validation_files,
        )

        signature = patch_signature(patch)
        score, notes = score_patch_prevalidation(
            patch=patch,
            valid=valid,
            n_errors=n_errors,
            n_warnings=n_warnings,
        )

        records.append(
            CandidateRecord(
                candidate_id=candidate_id,
                patch_path=str(patch_path),
                validation_path=validation_path,
                valid=valid,
                n_errors=n_errors,
                n_warnings=n_warnings,
                patch_signature=signature,
                screening_score=score,
                selected=False,
                targeted_failures=get_targeted_failures(patch),
                warnings=warnings,
                errors=errors,
                notes=notes,
            )
        )

    return records


def mark_duplicates(records: list[CandidateRecord]) -> list[CandidateRecord]:
    """
    Mark duplicate candidates based on semantic patch signature.

    The highest-scoring candidate for a given signature is kept as canonical.
    """
    by_signature: dict[str, list[CandidateRecord]] = {}

    for record in records:
        by_signature.setdefault(record.patch_signature, []).append(record)

    updated: list[CandidateRecord] = []

    for signature, group in by_signature.items():
        group_sorted = sorted(
            group,
            key=lambda r: (-r.screening_score, r.n_errors, r.n_warnings, r.candidate_id),
        )
        canonical = group_sorted[0]

        for idx, record in enumerate(group_sorted):
            if idx == 0:
                updated.append(record)
            else:
                updated.append(
                    CandidateRecord(
                        candidate_id=record.candidate_id,
                        patch_path=record.patch_path,
                        validation_path=record.validation_path,
                        valid=record.valid,
                        n_errors=record.n_errors,
                        n_warnings=record.n_warnings,
                        patch_signature=record.patch_signature,
                        screening_score=record.screening_score,
                        duplicate_of=canonical.candidate_id,
                        selected=False,
                        rank=None,
                        targeted_failures=record.targeted_failures,
                        warnings=record.warnings,
                        errors=record.errors,
                        notes=record.notes + [f"duplicate_of={canonical.candidate_id}"],
                    )
                )

    return updated


def screen_candidates(
    *,
    patch_dir_or_file: str | Path,
    validation_dir_or_file: str | Path,
    max_candidates: int = 4,
    allow_warnings: bool = True,
    keep_duplicates: bool = False,
) -> list[CandidateRecord]:
    patch_files = find_patch_files(patch_dir_or_file)
    validation_files = find_validation_files(validation_dir_or_file)

    records = build_candidate_records(
        patch_files=patch_files,
        validation_files=validation_files,
    )
    records = mark_duplicates(records)

    eligible = []

    for record in records:
        if not record.valid:
            continue

        if not allow_warnings and record.n_warnings > 0:
            continue

        if not keep_duplicates and record.duplicate_of is not None:
            continue

        eligible.append(record)

    eligible = sorted(
        eligible,
        key=lambda r: (-r.screening_score, r.n_errors, r.n_warnings, r.candidate_id),
    )

    selected_ids = {record.candidate_id for record in eligible[:max_candidates]}

    final_records: list[CandidateRecord] = []
    rank = 1

    for record in sorted(
        records,
        key=lambda r: (-r.screening_score, r.n_errors, r.n_warnings, r.candidate_id),
    ):
        is_selected = record.candidate_id in selected_ids
        assigned_rank = rank if is_selected else None

        if is_selected:
            rank += 1

        final_records.append(
            CandidateRecord(
                candidate_id=record.candidate_id,
                patch_path=record.patch_path,
                validation_path=record.validation_path,
                valid=record.valid,
                n_errors=record.n_errors,
                n_warnings=record.n_warnings,
                patch_signature=record.patch_signature,
                screening_score=record.screening_score,
                duplicate_of=record.duplicate_of,
                selected=is_selected,
                rank=assigned_rank,
                targeted_failures=record.targeted_failures,
                warnings=record.warnings,
                errors=record.errors,
                notes=record.notes,
            )
        )

    return final_records


