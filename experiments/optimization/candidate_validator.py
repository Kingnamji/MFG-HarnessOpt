def read_json(path: str | Path) -> dict[str, Any]:
    path = Path(path)

    if not path.exists():
        raise FileNotFoundError(f"Patch JSON file not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, dict):
        raise TypeError(f"Patch JSON must contain an object/dict: {path}")

    return data


def write_json(path: str | Path, obj: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with path.open("w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2, default=str)


def find_patch_files(path: str | Path) -> list[Path]:
    path = Path(path)

    if path.is_file():
        return [path]

    if not path.exists():
        raise FileNotFoundError(f"Patch path not found: {path}")

    patch_files = sorted(path.glob("*_patch.json"))

    if not patch_files:
        patch_files = sorted(path.glob("*.json"))

    return patch_files


def stringify(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False, default=str).lower()


# ============================================================
# Issue helpers
# ============================================================

def error(code: str, message: str, location: str = "") -> ValidationIssue:
    return ValidationIssue(
        severity="error",
        code=code,
        message=message,
        location=location,
    )


def warning(code: str, message: str, location: str = "") -> ValidationIssue:
    return ValidationIssue(
        severity="warning",
        code=code,
        message=message,
        location=location,
    )


def split_issues(issues: list[ValidationIssue]) -> tuple[list[ValidationIssue], list[ValidationIssue]]:
    errors = [issue for issue in issues if issue.severity == "error"]
    warnings = [issue for issue in issues if issue.severity == "warning"]
    return errors, warnings


