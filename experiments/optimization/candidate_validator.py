"""
Candidate validator for M4 harness patches.

This module validates candidate patch JSON files generated by:

    experiments/optimization/harness_proposer.py

The validator is intentionally conservative. It checks that a proposed patch:
- only modifies allowed harness configuration modules,
- does not expose hidden supports annotations to the LLM input,
- does not modify datasets, gold labels, evaluator, metric definitions, proxy
  evidence builders, candidate labels, or test split,
- contains the required patch structure for later validation/final runners.

Typical input:
    outputs/search/<run_name>/proposals/M4_candidate_xxx_patch.json

Typical output:
    outputs/search/<run_name>/validated_candidates/
    ├─ candidate_validation_results.csv
    └─ M4_candidate_xxx_validation.json
"""

