def validate_required_fields(patch: dict[str, Any]) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    missing = sorted(REQUIRED_TOP_LEVEL_FIELDS - set(patch.keys()))
    if missing:
        issues.append(
            error(
                "missing_required_fields",
                f"Patch is missing required top-level fields: {missing}",
                "root",
            )
        )

    return issues


def validate_candidate_identity(patch: dict[str, Any], patch_path: str | Path) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    candidate_id = patch.get("candidate_id")
    if not candidate_id:
        issues.append(error("missing_candidate_id", "candidate_id is empty or missing.", "candidate_id"))
    elif not isinstance(candidate_id, str):
        issues.append(error("invalid_candidate_id_type", "candidate_id must be a string.", "candidate_id"))

    base_method = patch.get("base_method")
    if base_method != "M3":
        issues.append(
            warning(
                "unexpected_base_method",
                f"Expected base_method='M3' for current M4 patch, got {base_method!r}.",
                "base_method",
            )
        )

    return issues


def validate_editable_and_frozen_modules(patch: dict[str, Any]) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    editable_modules = set(patch.get("editable_modules", []))
    frozen_modules = set(patch.get("frozen_modules", []))

    unknown_editable = sorted(editable_modules - ALLOWED_EDITABLE_MODULES)
    if unknown_editable:
        issues.append(
            error(
                "unknown_editable_modules",
                f"Patch includes unknown editable modules: {unknown_editable}",
                "editable_modules",
            )
        )

    missing_editable = sorted(ALLOWED_EDITABLE_MODULES - editable_modules)
    if missing_editable:
        issues.append(
            warning(
                "missing_editable_modules",
                f"Patch omits editable modules: {missing_editable}",
                "editable_modules",
            )
        )

    missing_frozen = sorted(REQUIRED_FROZEN_MODULES - frozen_modules)
    if missing_frozen:
        issues.append(
            error(
                "missing_frozen_modules",
                f"Patch must list these frozen modules: {missing_frozen}",
                "frozen_modules",
            )
        )

    # Frozen modules must not also appear as editable.
    overlap = sorted(editable_modules & frozen_modules)
    if overlap:
        issues.append(
            error(
                "editable_frozen_overlap",
                f"Modules cannot be both editable and frozen: {overlap}",
                "editable_modules/frozen_modules",
            )
        )

    return issues


def validate_evidence_table_format(patch: dict[str, Any]) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    evidence_format = patch.get("evidence_table_format", {})
    if not isinstance(evidence_format, dict):
        return [
            error(
                "invalid_evidence_table_format",
                "evidence_table_format must be a dictionary.",
                "evidence_table_format",
            )
        ]

    proposed_columns = evidence_format.get("proposed_columns", [])
    forbidden_columns = evidence_format.get("forbidden_columns", [])

    if not isinstance(proposed_columns, list):
        issues.append(
            error(
                "invalid_proposed_columns",
                "evidence_table_format.proposed_columns must be a list.",
                "evidence_table_format.proposed_columns",
            )
        )
        proposed_columns = []

    if not isinstance(forbidden_columns, list):
        issues.append(
            error(
                "invalid_forbidden_columns",
                "evidence_table_format.forbidden_columns must be a list.",
                "evidence_table_format.forbidden_columns",
            )
        )
        forbidden_columns = []

    proposed_set = {str(c) for c in proposed_columns}
    forbidden_set = {str(c) for c in forbidden_columns}

    leaked_columns = sorted(proposed_set & FORBIDDEN_INPUT_EVIDENCE_COLUMNS)
    if leaked_columns:
        issues.append(
            error(
                "forbidden_input_evidence_columns",
                f"Patch proposes forbidden LLM input evidence columns: {leaked_columns}",
                "evidence_table_format.proposed_columns",
            )
        )

    if "supports" not in forbidden_set:
        issues.append(
            error(
                "supports_not_forbidden",
                "evidence_table_format.forbidden_columns must include 'supports'.",
                "evidence_table_format.forbidden_columns",
            )
        )

    missing_required_columns = sorted(REQUIRED_EVIDENCE_TABLE_COLUMNS - proposed_set)
    if missing_required_columns:
        issues.append(
            error(
                "missing_recommended_evidence_columns",
                f"Patch omits recommended evidence table columns: {missing_required_columns}",
                "evidence_table_format.proposed_columns",
            )
        )

    return issues


def validate_action_filter_rules(patch: dict[str, Any]) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    action_filter = patch.get("action_filter_rules", {})
    if not isinstance(action_filter, dict):
        return [
            error(
                "invalid_action_filter_rules",
                "action_filter_rules must be a dictionary.",
                "action_filter_rules",
            )
        ]

    rules = action_filter.get("rules", [])
    out_of_scope_actions = action_filter.get("out_of_scope_actions", [])

    if not isinstance(rules, list):
        issues.append(
            error(
                "invalid_action_rules",
                "action_filter_rules.rules must be a list.",
                "action_filter_rules.rules",
            )
        )
        rules = []

    if not isinstance(out_of_scope_actions, list):
        issues.append(
            error(
                "invalid_out_of_scope_actions",
                "action_filter_rules.out_of_scope_actions must be a list.",
                "action_filter_rules.out_of_scope_actions",
            )
        )
        out_of_scope_actions = []

    out_of_scope_set = {str(x) for x in out_of_scope_actions}
    missing_out_of_scope = sorted(OUT_OF_SCOPE_ACTIONS - out_of_scope_set)
    if missing_out_of_scope:
        issues.append(
            warning(
                "missing_out_of_scope_actions",
                f"Patch should explicitly keep these actions out-of-scope: {missing_out_of_scope}",
                "action_filter_rules.out_of_scope_actions",
            )
        )

    rules_text = " ".join(str(r) for r in rules).lower()
    if "rationale_evidence" not in rules_text and "evidence_id" not in rules_text:
        issues.append(
            warning(
                "action_rules_do_not_mention_evidence_ids",
                "Action filter rules should mention evidence IDs or rationale_evidence_ids.",
                "action_filter_rules.rules",
            )
        )

    return issues


def validate_repair_configuration(patch: dict[str, Any]) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    repair_prompt = patch.get("repair_prompt", {})
    repair_triggers = patch.get("repair_trigger_thresholds", {})

    if not isinstance(repair_prompt, dict):
        issues.append(
            error(
                "invalid_repair_prompt",
                "repair_prompt must be a dictionary.",
                "repair_prompt",
            )
        )

    if not isinstance(repair_triggers, dict):
        issues.append(
            error(
                "invalid_repair_trigger_thresholds",
                "repair_trigger_thresholds must be a dictionary.",
                "repair_trigger_thresholds",
            )
        )
        return issues

    required_trigger_keys = ["schema_invalid", "F5", "F6", "F7", "F8", "unsafe_recommendation_rate_gt"]
    missing_triggers = [key for key in required_trigger_keys if key not in repair_triggers]
    if missing_triggers:
        issues.append(
            warning(
                "missing_repair_triggers",
                f"Patch omits recommended repair trigger keys: {missing_triggers}",
                "repair_trigger_thresholds",
            )
        )

    if "F10" in repair_triggers:
        issues.append(
            warning(
                "f10_as_repair_trigger",
                "F10 is an outcome of repair failure and should usually not be a direct pre-repair trigger.",
                "repair_trigger_thresholds.F10",
            )
        )

    return issues


def validate_sensitive_terms_context(patch: dict[str, Any]) -> list[ValidationIssue]:
    """
    Context-aware guardrail validation.

    We allow sensitive terms in:
    - frozen_modules
    - forbidden_columns
    - statements that explicitly say "do not", "must not", "without changing",
      or "keep ... fixed"

    We reject dangerous imperative patterns such as "use gold_label" or
    "modify evaluator".
    """
    issues: list[ValidationIssue] = []
    patch_text = stringify(patch)

    for pattern in DANGEROUS_PATTERNS:
        matches=list(re.finditer(pattern,patch_text,flags=re.IGNORECASE))
        # An explicit prohibition is not a request to perform the prohibited
        # action. Check each match locally so a later positive imperative is
        # still rejected even when another sentence says "do not".
        positive=[m for m in matches if not re.search(r"\b(?:do not|must not|should not|may not|never|cannot|don't)\s*$",patch_text[max(0,m.start()-32):m.start()])]
        if positive:
            issues.append(
                error(
                    "dangerous_forbidden_pattern",
                    f"Patch text matches forbidden pattern: {pattern}",
                    "patch_text",
                )
            )

    # Softer warnings for sensitive terms not covered above.
    # These are warnings only because legitimate patches mention frozen terms
    # to state they remain fixed.
    for term in SENSITIVE_TERMS:
        if term.lower() not in patch_text:
            continue

        # Legitimate locations.
        if term in {"evaluator", "metric definitions", "gold_labels", "hidden supports"}:
            continue

        if term.lower() in {"gold_label"}:
            # output/metadata references may include gold_label in traces, but
            # patch should not normally mention it outside frozen constraints.
            issues.append(
                warning(
                    "sensitive_term_present",
                    f"Sensitive term appears in patch text: {term}",
                    "patch_text",
                )
            )

    return issues


def _direction_remapping_is_prohibited(statement: str, match_start: int) -> bool:
    """Recognize direct prohibitions and shared negation in an or/nor verb list.

    Negation stays within one clause and one patch string. Unrecognized or
    ambiguous wording remains rejected; this is not a general prose parser.
    In particular, a prohibition must not authorize a later positive command.
    """
    prefix = statement[:match_start].lower().replace('\u2019', "'")
    clause = re.split(
        r'[.;:!?\n]|\b(?:but|however|instead|yet|then|otherwise|unless|except|'
        r'although|though|because|if|when|while|whereas|until|once|provided)\b',
        prefix,
    )[-1]
    negation = (
        r"\b(?:do\s+not|must\s+not|should\s+not|may\s+not|shall\s+not|"
        r"can\s+not|cannot|can't|don't|mustn't|shouldn't|never|neither)\b"
    )
    direct = re.search(negation + r'\s+(?:ever\s+)?$', clause)
    if direct:
        return not re.search(negation + r'\s+(?:ever\s+)?$', clause[:direct.start()])
    coordinator = re.search(r'\b(?:or|nor)\s+(?:ever\s+)?$', clause)
    if coordinator is None:
        return False
    negatives = list(re.finditer(negation, clause[:coordinator.start()]))
    if not negatives:
        return False
    scope = clause[negatives[-1].end():coordinator.start()]
    # A quote after the negator, a new subject/modal, or another negation does
    # not establish a shared negative imperative. Keep such cases blocked.
    if not re.match(r'\s+[a-z]', scope):
        return False
    if re.search(
        r'\b(?:only|merely|not|also|must|should|shall|may|might|can|could|will|'
        r'would|is|are|was|were|am|you|we|they|it|let)\b', scope,
    ):
        return False
    return True


def validate_patch_semantics(patch: dict[str, Any]) -> list[ValidationIssue]:
    """
    Lightweight semantic checks for current M4 candidate patch.
    """
    issues: list[ValidationIssue] = []
    from experiments.optimization.patch_contract import patch_contract_violations
    issues.extend(error(v['code'], v['message'], v['location'])
                  for v in patch_contract_violations(patch))

    # Prompt instructions should not instruct to add hidden supports to input.
    prompt_instructions = patch.get("prompt_instructions", {})
    prompt_text = stringify(prompt_instructions)

    statements=[str(s).lower() for values in prompt_instructions.values() for s in (values if isinstance(values,list) else [values])]
    exposure=False
    for statement in statements:
        for match in re.finditer(r'(?:include|expose|add|read|copy)\s+(?:hidden\s+)?supports[^.]{0,80}\binput\b',statement):
            if not re.search(r"\b(?:do not|must not|never|cannot|don't)\s*$",statement[max(0,match.start()-30):match.start()]):exposure=True
    if exposure:
        issues.append(
            error(
                "prompt_exposes_supports",
                "prompt_instructions appear to expose supports in input context.",
                "prompt_instructions",
            )
        )

    # But output evidence can still require supports. This validator does not
    # block output-supports unless it is tied to input exposure.
    evidence_format = patch.get("evidence_table_format", {})
    formatting_rules_text = stringify(evidence_format.get("formatting_rules", []))

    if "do not include supports" not in formatting_rules_text and "supports" not in stringify(evidence_format.get("forbidden_columns", [])):
        issues.append(
            warning(
                "anti_leakage_rule_not_explicit",
                "Patch should explicitly state that supports is not included in LLM input evidence table.",
                "evidence_table_format",
            )
        )

    executable={k:patch.get(k,{}) for k in ['source_policy','prompt_instructions','repair_prompt']}
    body=stringify(executable)
    if re.search(r'\b(?:prefer|default to)\s+no[ -]failure\b',body):
        issues.append(warning('diagnostic_default_bias','Patch introduces a No Failure preference; paired diagnostic acceptance is required.','prompt_instructions'))
    for match in re.finditer(r'\b(?:ignore|override|disable)\s+(?:the\s+)?(?:label decision guide|common record contract)',body):
        if not re.search(r'\b(?:do not|must not|never|cannot)\s*$',body[max(0,match.start()-30):match.start()]):
            issues.append(error('overrides_common_contract','Patch cannot override the common contract.','prompt_instructions'))
    # Explicit blanket remapping conflicts with source-owned direction tags.
    # This is a narrow structural check, not a claim to validate arbitrary prose.
    consumed={k:patch.get(k,{}) for k in ['source_policy','evidence_table_format','prompt_instructions','repair_prompt']}
    def strings(value):
        if isinstance(value,str):yield value.lower()
        elif isinstance(value,dict):
            for v in value.values():yield from strings(v)
        elif isinstance(value,list):
            for v in value:yield from strings(v)
    for statement in strings(consumed):
        for match in re.finditer(r'\b(?:replace|convert|normalize|map|rewrite|change)\s+(?:direction\s+)?[\'\"]?normal[\'\"]?\s+(?:with|to|as)\s+[\'\"]?observed\b',statement):
            if not _direction_remapping_is_prohibited(statement, match.start()):
                issues.append(error('direction_remapping','Patch must preserve each observation\'s direction rather than map normal to observed.','prompt_instructions'))
        if 'do not partially edit mismatched rows' in statement:
            issues.append(warning('whole_row_rewrite','Whole-row repair can corrupt already correct fields; shared minimal-repair rules take precedence.','repair_prompt'))
    return issues


