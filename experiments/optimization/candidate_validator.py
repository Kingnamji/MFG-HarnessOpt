def validate_candidate_patch(
    patch_path: str | Path,
    *,
    strict: bool = True,
) -> CandidateValidationResult:
    patch_path = Path(patch_path)
    patch = read_json(patch_path)

    return validate_candidate_patch_data(patch,patch_path=patch_path,strict=strict)


def validate_candidate_patch_data(patch: dict[str, Any], *, patch_path: str | Path = 'in_memory_patch.json', strict: bool = True) -> CandidateValidationResult:
    """The same semantic checks before a generated patch is made executable."""
    patch_path = Path(patch_path)

    issues: list[ValidationIssue] = []
    issues.extend(validate_required_fields(patch))
    issues.extend(validate_candidate_identity(patch, patch_path))
    issues.extend(validate_editable_and_frozen_modules(patch))
    issues.extend(validate_evidence_table_format(patch))
    issues.extend(validate_action_filter_rules(patch))
    issues.extend(validate_repair_configuration(patch))
    issues.extend(validate_sensitive_terms_context(patch))
    issues.extend(validate_patch_semantics(patch))

    errors, warnings = split_issues(issues)

    candidate_id = str(patch.get("candidate_id", patch_path.stem.replace("_patch", "")))

    summary = {
        "candidate_id": candidate_id,
        "base_method": patch.get("base_method"),
        "editable_modules": patch.get("editable_modules", []),
        "frozen_modules": patch.get("frozen_modules", []),
        "evidence_columns": patch.get("evidence_table_format", {}).get("proposed_columns", []),
        "forbidden_columns": patch.get("evidence_table_format", {}).get("forbidden_columns", []),
        "repair_triggers": patch.get("repair_trigger_thresholds", {}),
        "targeted_failure_reductions": patch.get("expected_effects", {}).get("targeted_failure_reductions", []),
    }

    valid = len(errors) == 0

    return CandidateValidationResult(
        candidate_id=candidate_id,
        patch_path=str(patch_path),
        valid=valid,
        n_errors=len(errors),
        n_warnings=len(warnings),
        errors=[issue.to_dict() for issue in errors],
        warnings=[issue.to_dict() for issue in warnings],
        summary=summary,
    )


def validate_candidate_patches(
    patch_path_or_dir: str | Path,
    *,
    output_dir: str | Path | None = None,
    strict: bool = True,
) -> list[CandidateValidationResult]:
    patch_files = find_patch_files(patch_path_or_dir)

    results = [
        validate_candidate_patch(path, strict=strict)
        for path in patch_files
    ]

    if output_dir is not None:
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        rows = []
        for result in results:
            result_path = output_dir / f"{result.candidate_id}_validation.json"
            write_json(result_path, result.to_dict())

            rows.append(
                {
                    "candidate_id": result.candidate_id,
                    "patch_path": result.patch_path,
                    "valid": result.valid,
                    "n_errors": result.n_errors,
                    "n_warnings": result.n_warnings,
                    "errors": json.dumps(result.errors, ensure_ascii=False),
                    "warnings": json.dumps(result.warnings, ensure_ascii=False),
                }
            )

        summary_df = pd.DataFrame(rows)
        summary_df.to_csv(output_dir / "candidate_validation_results.csv", index=False)

    return results


# ============================================================
# CLI
# ============================================================

def main() -> None:
    parser = argparse.ArgumentParser(description="Validate M4 candidate patch JSON files.")

    parser.add_argument(
        "--patch",
        required=True,
        help="Path to a patch JSON file or directory containing *_patch.json files.",
    )
    parser.add_argument(
        "--output-dir",
        default=None,
        help="Optional directory for validation JSON/CSV outputs.",
    )
    parser.add_argument(
        "--non-strict",
        action="store_true",
        help="Reserved for future relaxed validation. Current checks are unchanged.",
    )

    args = parser.parse_args()

    results = validate_candidate_patches(
        args.patch,
        output_dir=args.output_dir,
        strict=not args.non_strict,
    )

    print("=== Candidate Validation Results ===")

    for result in results:
        status = "VALID" if result.valid else "INVALID"
        print(
            f"{result.candidate_id}: {status} "
            f"(errors={result.n_errors}, warnings={result.n_warnings})"
        )

        if result.errors:
            print("  Errors:")
            for issue in result.errors:
                print(f"  - [{issue['code']}] {issue['message']} ({issue.get('location', '')})")

        if result.warnings:
            print("  Warnings:")
            for issue in result.warnings:
                print(f"  - [{issue['code']}] {issue['message']} ({issue.get('location', '')})")

    if args.output_dir:
        print("\nSaved validation outputs:")
        print(f"- {Path(args.output_dir) / 'candidate_validation_results.csv'}")


if __name__ == "__main__":
    main()
